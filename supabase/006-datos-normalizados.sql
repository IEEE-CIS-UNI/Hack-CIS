-- ---------------------------------------------------------------------------
-- Datos normalizados: carrera de un catálogo, ciclo del 1 al 10, y reglas que
-- impiden que entre texto suelto.
--
-- CORRER DESPUÉS de 004 (y de 005 si ya se corrió). Es idempotente.
--
-- Qué cambia
--   · `careers`: catálogo de carreras. Se elige de una lista; quien no se
--     encuentra marca «Otra» y escribe la suya (`career_other`, ya limpia).
--     Antes `people.career` era texto libre y «Sistemas», «Ing. de Sistemas» e
--     «Ingeniería de Sistemas» contaban como carreras distintas.
--   · `people.cycle` (antes `study_year`): CICLO, del 1 al 10.
--   · Reglas en la base para que lo que se guarde ya venga limpio: correo en
--     minúsculas, celular en formato internacional, nombre sin espacios sobrantes.
--   · El equipo exige 2 carreras distintas de verdad (por id de catálogo).
--   · Contacto opcional (LinkedIn, GitHub, Discord) en un formato único, y «cómo te
--     enteraste» con opciones fijas.
--
-- Qué se borra por no usarse hoy
--   · people.career (texto libre; se migra a career_id/career_other y se borra)
--   · people.qr_token (el QR de ingreso se quitó; se vuelve a crear cuando haga falta)
--   · people.expertise_id y la tabla expertises (nada las usa)
-- ---------------------------------------------------------------------------

