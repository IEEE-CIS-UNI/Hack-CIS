  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'people' and column_name = 'study_year') then
    alter table public.people rename column study_year to cycle;
  end if;
end $$;

alter table public.people add column if not exists cycle smallint;
alter table public.people drop constraint if exists people_study_year_check;
alter table public.people drop constraint if exists people_cycle_check;
alter table public.people add  constraint people_cycle_check check (cycle is null or cycle between 1 and 10);

-- Lo que ya estaba como texto libre: se asigna a la carrera del catálogo cuyo
-- nombre coincide (sin tildes ni mayúsculas); el resto pasa a «Otra» con su texto.
do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'people' and column_name = 'career') then

    update public.people p
       set career_id = c.id
      from public.careers c
     where p.career_id is null and p.career is not null
       and lower(translate(c.name, 'áéíóúÁÉÍÓÚñÑ', 'aeiouaeiounn'))
         = lower(translate(btrim(p.career), 'áéíóúÁÉÍÓÚñÑ', 'aeiouaeiounn'));

    update public.people p
       set career_id = (select id from public.careers where slug = 'otra'),
           career_other = left(initcap(btrim(regexp_replace(p.career, '\s+', ' ', 'g'))), 60)
     where p.career_id is null and p.career is not null and btrim(p.career) <> '';

    alter table public.people drop column career;
  end if;
end $$;

